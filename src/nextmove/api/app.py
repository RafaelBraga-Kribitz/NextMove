"""Headless HTTP API (E1): `POST /v1/decisions`, `GET /v1/customers/{id}`, `POST /v1/overrides`,
plus read-only evaluation endpoints. OpenAPI is generated by FastAPI and exported to
`docs/api/openapi.json` (`just openapi`).

Run locally: `just serve` (profile and data root from `NEXTMOVE_PROFILE`, default `demo`, and
`NEXTMOVE_DATA_ROOT`, default the repository's `data/`). Single process, single container
(ADR-001); no authentication, because it serves simulated data on localhost only.
"""

from __future__ import annotations

import os
from datetime import date
from pathlib import Path

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field

from nextmove.api.demo import register_demo
from nextmove.api.service import DecisionService, NotFound, OverrideRejected
from nextmove.config.loader import load_config
from nextmove.decisions.contract import CONTRACT_VERSION, Decision

__all__ = ["create_app"]


class DecisionRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    customer_id: str = Field(min_length=1, examples=["42"])
    as_of: date | None = Field(
        default=None, description="Decision date; defaults to the first test-window day."
    )


class OverrideRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    decision_id: str = Field(min_length=1)
    customer_id: str = Field(min_length=1)
    as_of: date
    override_candidate: str = Field(min_length=1, examples=["email_delayed"])
    reason: str = Field(min_length=3, max_length=500)
    operator: str = Field(min_length=1, max_length=100)


def create_app(profile: str | None = None, root: Path | None = None) -> FastAPI:
    profile = profile or os.environ.get("NEXTMOVE_PROFILE", "demo")
    env_root = os.environ.get("NEXTMOVE_DATA_ROOT")
    root = root if root is not None else (Path(env_root) if env_root else None)
    app = FastAPI(
        title="NextMove decision API",
        version=CONTRACT_VERSION,
        description=(
            "Next-best-action decisions with reasons, constraints and overrides. Serves a "
            "seeded simulated retailer only (ADR-004); no real customer data."
        ),
    )
    state: dict[str, DecisionService] = {}

    def service() -> DecisionService:
        if "svc" not in state:
            state["svc"] = DecisionService(load_config(profile), root)
        return state["svc"]

    app.state.service = service

    @app.get("/health", tags=["system"])
    def health() -> dict:
        return {"status": "ok", "profile": profile, "contract_version": CONTRACT_VERSION}

    @app.post("/v1/decisions", response_model=Decision, tags=["decisions"])
    def decide(request: DecisionRequest) -> Decision:
        svc = service()
        try:
            return svc.decide(request.customer_id, request.as_of or svc.default_as_of())
        except NotFound as error:
            raise HTTPException(status_code=404, detail=str(error)) from error

    @app.get("/v1/customers/{customer_id}", tags=["customers"])
    def customer(customer_id: str, as_of: date | None = None) -> dict:
        svc = service()
        try:
            return svc.customer(customer_id, as_of or svc.default_as_of())
        except NotFound as error:
            raise HTTPException(status_code=404, detail=str(error)) from error

    @app.get("/v1/customers/{customer_id}/options", tags=["customers"])
    def options(customer_id: str, as_of: date | None = None) -> list[dict]:
        svc = service()
        try:
            return svc.candidates(customer_id, as_of or svc.default_as_of())
        except NotFound as error:
            raise HTTPException(status_code=404, detail=str(error)) from error

    @app.post("/v1/overrides", status_code=201, tags=["overrides"])
    def override(request: OverrideRequest) -> dict:
        svc = service()
        try:
            return svc.record_override(**request.model_dump())
        except NotFound as error:
            raise HTTPException(status_code=404, detail=str(error)) from error
        except OverrideRejected as error:
            raise HTTPException(status_code=422, detail=str(error)) from error

    @app.get("/v1/evaluation/overrides", tags=["evaluation"])
    def override_evaluation() -> dict:
        return service().override_evaluation()

    @app.get("/v1/evaluation/policies", tags=["evaluation"])
    def policies() -> list[dict]:
        return service().policy_summary()

    register_demo(app, service)
    return app
